-- Schemat dla testów integracyjnych (tests/conftest.py przekierowuje
-- schemat fitness na fitness_test przez schema_translate_map).
-- Struktura musi odpowiadać tabelom z migracji Alembic w schemacie fitness.
-- Skrypt można uruchamiać wielokrotnie.

CREATE SCHEMA IF NOT EXISTS fitness_test;

DO $$
BEGIN
    IF to_regtype('fitness_test.typ_zajec') IS NULL THEN
        CREATE TYPE fitness_test.typ_zajec AS ENUM ('grupowe', 'indywidualne');
    END IF;

    IF to_regtype('fitness_test.poziom_zajec') IS NULL THEN
        CREATE TYPE fitness_test.poziom_zajec AS ENUM (
            'poczatkujacy', 'sredni', 'zaawansowany'
        );
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS fitness_test.klienci (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imie VARCHAR(60) NOT NULL,
    nazwisko VARCHAR(80) NOT NULL,
    email VARCHAR(254),
    telefon VARCHAR(30),
    utworzono_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fitness_test.trenerzy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imie VARCHAR(60) NOT NULL,
    nazwisko VARCHAR(80) NOT NULL,
    specjalizacja VARCHAR(120),
    utworzono_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fitness_test.sale (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa VARCHAR(80) NOT NULL UNIQUE,
    pojemnosc INTEGER NOT NULL,
    utworzono_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_sale_pojemnosc CHECK (pojemnosc > 0)
);

CREATE TABLE IF NOT EXISTS fitness_test.oferta_zajec (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa VARCHAR(120) NOT NULL,
    opis VARCHAR(1000),
    typ fitness_test.typ_zajec NOT NULL,
    poziom fitness_test.poziom_zajec,
    czas_trwania_min INTEGER NOT NULL,
    cena NUMERIC(8, 2) NOT NULL,
    limit_uczestnikow INTEGER NOT NULL,
    utworzono_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_oferta_zajec_czas CHECK (czas_trwania_min > 0),
    CONSTRAINT ck_oferta_zajec_cena CHECK (cena >= 0),
    CONSTRAINT ck_oferta_zajec_limit CHECK (limit_uczestnikow > 0),
    CONSTRAINT ck_oferta_zajec_indywidualne_limit
        CHECK (typ <> 'indywidualne' OR limit_uczestnikow = 1)
);

CREATE TABLE IF NOT EXISTS fitness_test.oferta_karnetow (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa VARCHAR(120) NOT NULL,
    cena NUMERIC(8, 2) NOT NULL,
    liczba_wejsc INTEGER,
    dni_waznosci INTEGER NOT NULL,
    utworzono_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_oferta_karnetow_cena CHECK (cena >= 0),
    CONSTRAINT ck_oferta_karnetow_wejscia
        CHECK (liczba_wejsc IS NULL OR liczba_wejsc > 0),
    CONSTRAINT ck_oferta_karnetow_dni CHECK (dni_waznosci > 0)
);
